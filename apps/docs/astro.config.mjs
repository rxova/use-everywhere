import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightTypeDoc, { typeDocSidebarGroup } from 'starlight-typedoc';
import starlightLinksValidator from 'starlight-links-validator';
import rehypeMermaid from 'rehype-mermaid';
import { sharedStarlightConfig } from '@rxova/brand';

/**
 * Defaults keep the standalone build working; the rxova.org aggregator sets
 * DOCS_URL / DOCS_BASE_URL to mount these docs under /packages/use-everywhere/.
 */
const site = process.env.DOCS_URL ?? 'https://rxova.org';
const base = process.env.DOCS_BASE_URL ?? '/';

/**
 * Three TypeDoc instances rather than one with three entry points — the same
 * split the Docusaurus setup used. Multiple entry points flip TypeDoc into
 * multi-module mode, which rewrites every API URL and would break every
 * existing inbound link.
 */
const typeDocDefaults = {
  typeDoc: {
    useCodeBlocks: true,
    disableSources: true,
    parametersFormat: 'table',
    enumMembersFormat: 'table',
  },
};

export default defineConfig({
  site,
  base,

  markdown: {
    // The Docusaurus site rendered mermaid via @docusaurus/theme-mermaid;
    // Starlight has no equivalent, so without this the two diagrams degrade
    // into syntax-highlighted code blocks.
    //
    // `inline-svg` renders them at build time with headless chromium, so the
    // diagrams ship as static SVG: no client-side mermaid bundle, nothing to
    // hydrate, and the output stays a plain static tree the aggregator can
    // mount. Requires playwright's chromium in CI.
    rehypePlugins: [[rehypeMermaid, { strategy: 'inline-svg' }]],
  },
  integrations: [
    starlight({
      ...sharedStarlightConfig({
        project: 'use-everywhere',
        // These docs ship as a page component: rxova.org composes each rendered
        // body into its own header and footer, so this build must not draw the
        // umbrella footer itself. It was doing that by overriding Starlight's
        // `Footer` with a local wrapper around the default, and reconciling the
        // two sticky headers in a `page-component.css` of its own — both copies
        // of what @rxova/brand ships behind this flag since 0.9.0. One flag now
        // says what the build is, and the theme owns how that looks.
        pageComponent: true,
        customCss: ['./src/styles/mermaid.css'],
        // Starlight 0.39 removed `label` + `autogenerate` as siblings; an
        // autogenerated group now nests inside `items`. Order and labels here
        // reproduce the _category_.json files the Docusaurus site used.
        sidebar: [
          { label: 'Learn', items: [{ autogenerate: { directory: 'learn' } }] },
          { label: 'Hooks', items: [{ autogenerate: { directory: 'hooks' } }] },
          { label: 'Core (without React)', items: [{ autogenerate: { directory: 'core' } }] },
          { label: 'Guides', items: [{ autogenerate: { directory: 'guides' } }] },
          { label: 'ESLint plugin', items: [{ autogenerate: { directory: 'eslint' } }] },
          { label: 'Error codes', link: '/errors/' },
          {
            label: 'Under the hood',
            items: [{ autogenerate: { directory: 'under-the-hood' } }],
          },
          typeDocSidebarGroup,
        ],
      }),

      // Overrides the shared default of '/favicon.svg'. There is no vector
      // rxova mark yet — only the logo PNGs — so this site ships a downscaled
      // PNG generated from @rxova/brand's asset. Starlight resolves `favicon`
      // against this site's own public/ directory, so it cannot be served from
      // the package. Drop this line once @rxova/brand ships a mark the shared
      // config can point at directly.
      favicon: '/favicon.png',
      plugins: [
        starlightTypeDoc({
          ...typeDocDefaults,
          entryPoints: ['../../packages/core/src/index.ts'],
          tsconfig: '../../packages/core/tsconfig.json',
          output: 'api/core',
          sidebar: { label: 'Core API', collapsed: true },
        }),
        starlightTypeDoc({
          ...typeDocDefaults,
          entryPoints: ['../../packages/react/src/index.ts'],
          tsconfig: '../../packages/react/tsconfig.json',
          output: 'api/react',
          sidebar: { label: 'React API', collapsed: true },
        }),
        starlightTypeDoc({
          ...typeDocDefaults,
          entryPoints: ['../../packages/react/src/devtools/index.ts'],
          // packages/react is the only tsconfig setting `jsx`, and the devtools
          // entry re-exports Inspector from a .tsx file.
          tsconfig: '../../packages/react/tsconfig.json',
          output: 'api/devtools',
          sidebar: { label: 'Devtools API', collapsed: true },
        }),
        // Catches the failure mode this migration is most exposed to: 312
        // relative links written against Docusaurus's doc-id resolution.
        starlightLinksValidator({ errorOnRelativeLinks: false }),
      ],
    }),
  ],
});
